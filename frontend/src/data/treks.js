export const getTrekBySlug = (slug: string): Trek | undefined =>
  treks.find((t) => t.slug === slug)

export const getTrekById = (id: number): Trek | undefined =>
  treks.find((t) => t.id === id)

export const getTreksByState = (state: string): Trek[] =>
  treks.filter((t) => t.state === state)

export const getFeaturedTreks = (): Trek[] =>
  treks.filter((t) => t.featured)

export const getDifficultyColor = (difficulty: string): string => {
  switch (difficulty) {
    case 'Easy': return 'text-green-500 bg-green-100 dark:bg-green-900/30'
    case 'Moderate': return 'text-yellow-500 bg-yellow-100 dark:bg-yellow-900/30'
    case 'Difficult': return 'text-orange-500 bg-orange-100 dark:bg-orange-900/30'
    case 'Challenging': return 'text-red-500 bg-red-100 dark:bg-red-900/30'
    default: return 'text-gray-500 bg-gray-100'
  }
}
